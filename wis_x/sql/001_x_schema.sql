-- WIS X: esquema hermano de LinkedIn. Ejecutar en Supabase de la instalación de WIS.
-- No modifica posts_pending ni ninguno de los objetos usados por LinkedIn.

create table if not exists public.x_posts_pending (
  id bigint generated by default as identity primary key,
  platform text not null default 'x' check (platform = 'x'),
  noticia_id bigint,
  format text not null default 'single' check (format in ('single', 'thread')),
  posts_json jsonb not null,
  weighted_lengths_json jsonb not null,
  version integer not null default 1,
  estado text not null check (estado in ('draft_enviado','regenerando','aprobado','publicando','publicado','rechazado','vencido','error','outcome_unknown','partial_failure')),
  telegram_chat_id text,
  telegram_user_id text,
  telegram_msg_id text,
  feedback_ortu text,
  approval_received_at timestamptz,
  approval_expires_at timestamptz not null,
  x_post_ids_json jsonb not null default '[]'::jsonb,
  x_urls_json jsonb not null default '[]'::jsonb,
  published_at timestamptz,
  error_code text,
  error_message text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.x_publish_attempts (
  id bigint generated by default as identity primary key,
  pending_post_id bigint not null references public.x_posts_pending(id) on delete restrict,
  item_sequence integer not null check (item_sequence > 0),
  idempotency_key text not null,
  request_fingerprint text not null,
  estado text not null check (estado in ('started','success','error','outcome_unknown')),
  x_post_id text,
  response_status integer,
  response_body_sanitized jsonb,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (pending_post_id, item_sequence),
  unique (idempotency_key)
);

create unique index if not exists x_posts_pending_active_telegram_msg
  on public.x_posts_pending (telegram_msg_id)
  where telegram_msg_id is not null and estado in ('draft_enviado','regenerando','aprobado');

create unique index if not exists x_posts_pending_one_active_approval
  on public.x_posts_pending (id)
  where estado = 'aprobado' and approval_received_at is not null;

create index if not exists x_posts_pending_expiration_idx
  on public.x_posts_pending (approval_expires_at, estado);

create or replace function public.touch_x_posts_pending()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

drop trigger if exists trg_touch_x_posts_pending on public.x_posts_pending;
create trigger trg_touch_x_posts_pending before update on public.x_posts_pending
for each row execute function public.touch_x_posts_pending();

create or replace function public.claim_x_post_for_publish(p_pending_post_id bigint, p_now timestamptz default now())
returns public.x_posts_pending language plpgsql security definer set search_path = public as $$
declare claimed public.x_posts_pending;
begin
  update public.x_posts_pending
     set estado = 'publicando', approval_received_at = coalesce(approval_received_at, p_now)
   where id = p_pending_post_id
     and platform = 'x'
     and estado = 'aprobado'
     and approval_expires_at > p_now
  returning * into claimed;
  return claimed;
end;
$$;

create or replace function public.expire_x_posts(p_now timestamptz default now())
returns integer language plpgsql security definer set search_path = public as $$
declare changed integer;
begin
  update public.x_posts_pending set estado = 'vencido'
   where platform = 'x' and estado in ('draft_enviado','regenerando','aprobado')
     and approval_expires_at <= p_now;
  get diagnostics changed = row_count;
  return changed;
end;
$$;

-- El inbound debe llamar a esta función con la identidad validada por n8n.
-- La operación es atómica: un callback repetido no puede aprobar dos veces.
create or replace function public.approve_x_post_once(p_pending_post_id bigint, p_chat_id text, p_user_id text, p_message_id text, p_now timestamptz default now())
returns public.x_posts_pending language plpgsql security definer set search_path = public as $$
declare approved public.x_posts_pending;
begin
  update public.x_posts_pending
     set estado = 'aprobado', approval_received_at = p_now
   where id = p_pending_post_id and platform = 'x' and estado = 'draft_enviado'
     and approval_expires_at > p_now
     and telegram_chat_id = p_chat_id and telegram_user_id = p_user_id
     and (telegram_msg_id = p_message_id or p_message_id is null);
  if not found then return null; end if;
  select * into approved from public.x_posts_pending where id = p_pending_post_id;
  return approved;
end;
$$;
